/** Escapa dado de usuário antes de interpolar em HTML (e-mail, PDF, etc.) — nunca confiar em input livre. */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
